"""Where the bytes of the material library live (issue #33): a directory on a disk volume.

Layout under ``root``::

    staging/<upload id>.part              one file per upload in progress; chunks are written in place
    objects/<org id>/<aa>/<sha256>        one file per distinct content of an organisation

* No path contains anything an uploader chose. Upload ids and organisation ids
  are generated by the server, the object name is the SHA-256 the server
  computed, and all three are checked against a strict pattern before they are
  used in a path. A file name can therefore never address a place on the volume.
* Directories are 0700, a file is 0600 while it is being written and 0440 once
  stored. Nothing has an execute bit, nothing is extracted, and the directory
  is not served by any web server: stored files leave only through the API, as
  a download (``routes/library.py``).
* Chunk writers hold a shared ``flock`` on the staging file and the completion
  step an exclusive one, so the bytes that were hashed are the bytes that get
  stored — also with several server processes on the same volume. The lock is
  on the open file, not on its name: :meth:`LibraryStore.promote` therefore
  checks that the name still leads to the file it holds, before and after the
  move, and refuses (``StagingLost``) when it does not.

This class is the only code that touches the volume. Moving the library to
object storage means a second class with the same methods.
"""
from __future__ import annotations

import errno
import fcntl
import hashlib
import os
import re
import shutil
import threading
import time
from contextlib import contextmanager
from typing import Iterator

UPLOAD_ID = re.compile(r"upl_[0-9a-f]{20}")
ORG_ID = re.compile(r"org_[0-9a-f]{20}")
SHA256 = re.compile(r"[0-9a-f]{64}")
_PART = ".part"
_DIR_MODE, _STAGING_MODE, _OBJECT_MODE = 0o700, 0o600, 0o440
_READ_BLOCK = 1024 * 1024
_NOFOLLOW = getattr(os, "O_NOFOLLOW", 0) | getattr(os, "O_CLOEXEC", 0)


class StorageFull(Exception):
    """The volume has no room for the bytes."""


class StagingLost(Exception):
    """The upload's file is no longer the file under its name (removed or replaced meanwhile)."""


def _same_file(path: str, held: os.stat_result) -> bool:
    try:
        found = os.stat(path, follow_symlinks=False)
    except FileNotFoundError:
        return False
    return (found.st_ino, found.st_dev) == (held.st_ino, held.st_dev)


def _file_sha256(fd: int) -> str:
    digest, offset = hashlib.sha256(), 0
    while True:
        block = os.pread(fd, _READ_BLOCK, offset)
        if not block:
            return digest.hexdigest()
        digest.update(block)
        offset += len(block)


def _checked(pattern: re.Pattern, value: str, what: str) -> str:
    if not isinstance(value, str) or not pattern.fullmatch(value):
        raise ValueError(f"invalid {what} for a library path")
    return value


class Staging:
    """An upload's file while a lock on it is held (see :meth:`LibraryStore.staging`)."""

    def __init__(self, fd: int, path: str):
        self.fd, self.path = fd, path

    def write(self, offset: int, data: bytes) -> None:
        view = memoryview(data)
        try:
            while view:
                written = os.pwrite(self.fd, view, offset)
                offset += written
                view = view[written:]
        except OSError as exc:
            if exc.errno in (errno.ENOSPC, errno.EDQUOT):
                raise StorageFull() from None
            raise

    def size(self) -> int:
        return os.fstat(self.fd).st_size

    def sha256(self) -> str:
        return _file_sha256(self.fd)

    def is_current(self) -> bool:
        """Is the file held here still the one under the upload's name?"""
        return _same_file(self.path, os.fstat(self.fd))

    def sync(self) -> None:
        os.fsync(self.fd)


class LibraryStore:
    def __init__(self, root: str, max_verifications: int = 2):
        self.root = os.path.abspath(root)
        # Completing an upload reads the whole file (up to gigabytes): only a few at a time per process.
        self.verify_slots = threading.BoundedSemaphore(max(1, max_verifications))

    # ------------------------------------------------------------ paths
    def _staging_path(self, upload_id: str) -> str:
        return os.path.join(self.root, "staging", _checked(UPLOAD_ID, upload_id, "upload id") + _PART)

    def object_path(self, org_id: str, sha256: str) -> str:
        digest = _checked(SHA256, sha256, "digest")
        return os.path.join(self.root, "objects", _checked(ORG_ID, org_id, "organisation id"), digest[:2], digest)

    def _make_dir(self, path: str) -> None:
        """Create ``path`` (inside the root) and every missing parent, each 0700."""
        os.makedirs(self.root, mode=_DIR_MODE, exist_ok=True)
        current = self.root
        for part in os.path.relpath(path, self.root).split(os.sep):
            current = os.path.join(current, part)
            try:
                os.mkdir(current, _DIR_MODE)
            except FileExistsError:
                pass

    # ------------------------------------------------------------ uploads in progress
    @contextmanager
    def staging(self, upload_id: str, *, exclusive: bool, create: bool) -> Iterator[Staging]:
        """The upload's file, locked: shared for a chunk writer, exclusive for completion.

        ``FileNotFoundError`` when it does not exist and ``create`` is false."""
        path = self._staging_path(upload_id)
        flags = os.O_RDWR | _NOFOLLOW
        if create:
            self._make_dir(os.path.dirname(path))
            flags |= os.O_CREAT
        fd = os.open(path, flags, _STAGING_MODE)
        try:
            fcntl.flock(fd, fcntl.LOCK_EX if exclusive else fcntl.LOCK_SH)
            yield Staging(fd, path)
        finally:
            os.close(fd)                    # also releases the lock

    def discard(self, upload_id: str) -> None:
        self._unlink(self._staging_path(upload_id))

    def stale_staging(self, older_than_seconds: float) -> list[str]:
        """Ids of staging files not modified for ``older_than_seconds`` (candidates for a clean-up)."""
        directory = os.path.join(self.root, "staging")
        limit = time.time() - older_than_seconds
        found = []
        try:
            names = os.listdir(directory)
        except FileNotFoundError:
            return found
        for name in names:
            upload_id = name[:-len(_PART)] if name.endswith(_PART) else ""
            if not UPLOAD_ID.fullmatch(upload_id):
                continue
            try:
                if os.stat(os.path.join(directory, name)).st_mtime < limit:
                    found.append(upload_id)
            except FileNotFoundError:
                continue
        return found

    # ------------------------------------------------------------ stored files
    def object_matches(self, org_id: str, sha256: str) -> bool:
        """Does the organisation already store a file whose content really has this digest?"""
        try:
            fd = os.open(self.object_path(org_id, sha256), os.O_RDONLY | _NOFOLLOW)
        except FileNotFoundError:
            return False
        try:
            return _file_sha256(fd) == sha256
        finally:
            os.close(fd)

    def promote(self, staging: Staging, org_id: str, sha256: str, *, keep_existing: bool = False) -> str:
        """Make a verified staging file the stored object (call with its exclusive lock held).

        ``keep_existing``: the caller has checked (:meth:`object_matches`) that the
        organisation already stores this content; the stored file stays and the
        staging file goes. Otherwise the staging file is moved into place.
        ``StagingLost`` when the file that was verified is not the file under
        the upload's name: nothing is stored then."""
        target = self.object_path(org_id, sha256)
        held = os.fstat(staging.fd)
        if not _same_file(staging.path, held):
            raise StagingLost()
        if keep_existing and self.object_size(org_id, sha256) == held.st_size:
            os.unlink(staging.path)
            return target
        self._make_dir(os.path.dirname(target))
        os.fchmod(staging.fd, _OBJECT_MODE)
        os.replace(staging.path, target)
        if not _same_file(target, held):        # the name was switched between the check and the move
            self._unlink(target)
            raise StagingLost()
        self._sync_dir(os.path.dirname(target))
        return target

    @staticmethod
    def _unlink(path: str) -> None:
        try:
            os.unlink(path)
        except FileNotFoundError:
            pass

    @staticmethod
    def _sync_dir(path: str) -> None:
        try:
            fd = os.open(path, os.O_RDONLY)
        except OSError:
            return
        try:
            os.fsync(fd)
        except OSError:
            pass
        finally:
            os.close(fd)

    def object_size(self, org_id: str, sha256: str) -> int | None:
        try:
            return os.stat(self.object_path(org_id, sha256)).st_size
        except FileNotFoundError:
            return None

    def delete_object(self, org_id: str, sha256: str) -> None:
        # The (possibly empty) directories stay: removing them could pull the ground from under
        # another upload that is about to move its file into the same directory.
        self._unlink(self.object_path(org_id, sha256))

    def old_objects(self, older_than_seconds: float) -> list[tuple[str, str]]:
        """``(org id, sha256)`` of stored files not modified for ``older_than_seconds`` (for the orphan sweep)."""
        base, limit, found = os.path.join(self.root, "objects"), time.time() - older_than_seconds, []
        for directory, _dirs, names in os.walk(base):
            parts = os.path.relpath(directory, base).split(os.sep)
            if len(parts) != 2 or not ORG_ID.fullmatch(parts[0]):
                continue
            for name in names:
                if not SHA256.fullmatch(name) or name[:2] != parts[1]:
                    continue
                try:
                    if os.stat(os.path.join(directory, name)).st_mtime < limit:
                        found.append((parts[0], name))
                except FileNotFoundError:
                    continue
        return found

    # ------------------------------------------------------------ volume
    def free_bytes(self) -> int:
        path = self.root
        while not os.path.exists(path):
            parent = os.path.dirname(path)
            if parent == path:
                break
            path = parent
        return shutil.disk_usage(path).free
