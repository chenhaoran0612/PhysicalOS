import numpy as np

F32, F64 = np.float32, np.float64
R_LN2F = F32(1.442695040888963407359924681001892137426645954152985934135449406931)
L2UF, L2LF = F32(0.693145751953125), F32(1.428606765330187045e-06)
LIMIT = F32(8.664339742)                     # above this |x|, tanh is 1 in float32
EXP_POLY = (F32(0.1980960224e-3), F32(0.1394256484e-2), F32(0.8333456703e-2), F32(0.4166637361e-1))
SIXTH, HALF, ONE = F32(0.166666659414234244790680580464e+0), F32(0.5), F32(1)


def fma(a, b, c):
    """``a * b + c`` rounded once to float32 (the AdvSIMD ``vfmaq_f32``)."""
    product = a.astype(F64) * b.astype(F64)                  # exact: 24 + 24 bits fit in 53
    addend = np.asarray(c, dtype=F32).astype(F64)
    total = product + addend
    back = total - product
    error = (product - (total - back)) + (addend - back)      # total + error == product + addend, exactly
    result = total.astype(F32)
    up, down = np.nextafter(total, np.inf).astype(F32), np.nextafter(total, -np.inf).astype(F32)
    tie = (up != down) & (error != 0)                        # the float64 sum landed on a float32 midpoint
    return np.where(tie, np.where(error > 0, up, down), result) if np.any(tie) else result


# ------------------------------------------------------------ double-float helpers (df.h, ENABLE_FMA_SP)
def _add2_df_f(xx, xy, y):
    s = xx + y
    v = s - xx
    return s, ((xx - (s - v)) + (y - v)) + xy


def _add2_df_df(xx, xy, yx, yy):
    s = xx + yx
    v = s - xx
    return s, ((xx - (s - v)) + (yx - v)) + (xy + yy)


def _add_f_df(x, yx, yy):
    s = x + yx
    return s, ((x - s) + yx) + yy


def _add_df_df(xx, xy, yx, yy):
    s = xx + yx
    return s, (((xx - s) + yx) + xy) + yy


def _mul_df_f(xx, xy, y):
    s = xx * y
    return s, fma(xy, y, fma(xx, y, -s))


def _mul_df_df(xx, xy, yx, yy):
    s = xx * yx
    return s, fma(xx, yy, fma(xy, yx, fma(xx, yx, -s)))


def _square(xx, xy):
    s = xx * xx
    return s, fma(xx + xx, xy, fma(xx, xx, -s))


def _reciprocal(dx, dy):
    s = ONE / dx
    return s, s * fma(-dy, s, fma(-dx, s, ONE))


def _divide(nx, ny, dx, dy):
    t = ONE / dx
    s = nx * t
    u = fma(t, nx, -s)
    v = fma(-dy, t, fma(-dx, t, ONE))
    return s, fma(s, v, fma(ny, t, u))


def _ldexp2(d, e):
    half = e >> 1
    return (d * ((half + 0x7f).astype(np.int32) << 23).view(F32)) * (((e - half) + 0x7f).astype(np.int32) << 23).view(F32)


def _exp2f(dx, dy):
    """``expk2f``: e to the power of a double-float, as a double-float."""
    q = np.rint((dx + dy) * R_LN2F).astype(np.int32)
    qf = q.astype(F32)
    sx, sy = _add2_df_f(dx, dy, qf * -L2UF)
    sx, sy = _add2_df_f(sx, sy, qf * -L2LF)
    u = np.full_like(sx, EXP_POLY[0])
    for coefficient in EXP_POLY[1:]:
        u = fma(u, sx, coefficient)
    tx, ty = _add2_df_f(*_mul_df_f(sx, sy, u), SIXTH)
    tx, ty = _add2_df_f(*_mul_df_df(sx, sy, tx, ty), HALF)
    tx, ty = _add2_df_df(sx, sy, *_mul_df_df(*_square(sx, sy), tx, ty))
    tx, ty = _add_f_df(ONE, tx, ty)
    tx, ty = _ldexp2(tx, q), _ldexp2(ty, q)
    low = dx < F32(-104)
    return np.where(low, F32(0), tx), np.where(low, F32(0), ty)


def tanh(x):
    """``tanh`` of a float32 array, bit for bit as PyTorch's on an Apple-silicon CPU."""
    x = np.asarray(x, dtype=F32)
    with np.errstate(over='ignore', invalid='ignore', divide='ignore'):
        dx, dy = _exp2f(np.abs(x), np.zeros_like(x))
        ex, ey = _reciprocal(dx, dy)
        y = np.add(*_divide(*_add_df_df(dx, dy, -ex, -ey), *_add_df_df(dx, dy, ex, ey)))
        y = np.where((np.abs(x) > LIMIT) | np.isnan(y), ONE, y)
        return np.where(np.isnan(x), x, np.copysign(y, x)).astype(F32)


# ------------------------------------------------------------ atanh (``xatanhf``, ``logk2f``)
LN2_HI, LN2_LO = F32(0.69314718246459960938), F32(-1.904654323148236017e-09)
LOG_POLY = (F32(0.2392828464508056640625), F32(0.28518211841583251953125), F32(0.400005877017974853515625), F32(0.666666686534881591796875))


def _add2_f_f(x, y):
    s = x + y
    v = s - x
    return s, (x - (s - v)) + (y - v)


def _ilogb(d):
    small = d < F32(5.421010862427522e-20)
    d = np.where(small, F32(1.8446744073709552e19) * d, d)
    q = (d.view(np.int32) >> 23) & 0xff
    return q - np.where(small, 64 + 0x7f, 0x7f).astype(np.int32)


def _log2f(dx, dy):
    """``logk2f``: the natural logarithm of a double-float, as a double-float."""
    e = _ilogb(dx * F32(1.0 / 0.75)).astype(np.int32)
    scale = ((-e + 0x7f).astype(np.int32) << 23).view(F32)
    mx, my = dx * scale, dy * scale
    xx, xy = _divide(*_add2_df_f(mx, my, F32(-1)), *_add2_df_f(mx, my, F32(1)))
    x2x, x2y = _square(xx, xy)
    t = np.full_like(xx, LOG_POLY[0])
    for coefficient in LOG_POLY[1:]:
        t = fma(t, x2x, coefficient)
    sx, sy = _mul_df_f(np.full_like(xx, LN2_HI), np.full_like(xx, LN2_LO), e.astype(F32))
    sx, sy = _add_df_df(sx, sy, xx * F32(2), xy * F32(2))
    return _add_df_df(sx, sy, *_mul_df_f(*_mul_df_df(x2x, x2y, xx, xy), t))


def atanh(x):
    """``atanh`` of a float32 array, bit for bit as PyTorch's on an Apple-silicon CPU."""
    x = np.asarray(x, dtype=F32)
    with np.errstate(over='ignore', invalid='ignore', divide='ignore'):
        y = np.abs(x)
        dx, dy = _log2f(*_divide(*_add2_f_f(ONE, y), *_add2_f_f(ONE, -y)))
        y = np.where(y > ONE, F32(np.nan), np.where(y == ONE, F32(np.inf), (dx + dy) * F32(0.5)))
        y = np.where(np.isinf(x) | np.isnan(y), F32(np.nan), y)
        return np.where(np.isnan(x), x, np.copysign(y, x)).astype(F32)
