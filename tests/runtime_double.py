"""TEST DOUBLE of the runtime CLI ``neuxmind-runtime scaffold|conformance``
(INTERFACES §6.1/§6.2), used ONLY where the real runtime (``python -m neuxmind_runtime``,
runtime 09c1297) cannot run. It follows the real CLI shape, exit codes
(0 passed / 1 not passed / 2 refused, no report) and report fields:

  runtime_double.py scaffold --spec SPEC.json --out DIR
      SPEC = neuxmind.adapter_scaffold.v1 {name, vendor, model, family,
      instance_id, simulated, safety, capabilities:[{id, params, implementation, evidence_id}]}
      writes DIR/{pyproject.toml, README.md, tests/test_adapter.py,
      <name>/{__init__.py, adapter.py, adapter.json}} and prints a summary
      JSON with the load string ``adapter`` = "<name>.adapter:<Class>".
  runtime_double.py conformance --adapter <module>.adapter:<Class> --level static|dry --out FILE
      imports the package (PYTHONPATH) in this separate process and checks it
      against the real spec registry; writes conformance.report.v1 with
      ``<level>_ok``, ``levels.<level>.{requested, ran, ok, passed, failed,
      skipped, blocked, blocked_reasons}``, ``capabilities[]`` for every
      registry capability (``declared``, ``levels.<level>.{status, reason,
      skip_kind}``), ``cases[]``, ``field_acceptance: false``, ``disclaimer``.

It is deliberately small and honest: the generated adapter has a double
backend (``NEUXMIND_ADAPTER_BACKEND=double``) and raises NotImplementedError
otherwise; ``dry`` = spec-validated state reads, a zero ``base.velocity``,
idempotent ``safety.stop``. It never runs ``motion``, tests no latch/epoch, and
reports carry ``"double": true``. ``tests/test_adaptation.py`` checks its output
with the same strict parser as the real reports.
"""
import argparse
import importlib
import importlib.util
import json
from pathlib import Path
import sys
import time

sys.path.insert(0,str(Path(__file__).resolve().parents[1]/'spec'))
from neuxmind_spec import capabilities as caps  # noqa: E402

SAMPLE={'float':0.0,'int':1,'bool':True,'str':'double','floats':[0.0],'pose':[0,0,0,0,0,0,1],'blob_ref':'blob://double/0','object':{}}
ZERO={'base.velocity':{'vx':0.0,'wz':0.0}}
ROS2_TEMPLATES=('base.velocity','base.odometry','sensor.battery','sensor.imu','joint.state','localization.pose','base.navigate_to','safety.stop','system.health')


def sample(field):
    if field.type=='vector':return [0.0]*(field.length or 3)
    if field.type=='enum':return field.choices[0]
    if field.type=='object' and field.name=='names':return ['j1']
    return SAMPLE[field.type]


ADAPTER='''"""Generated by the NeuxMind runtime scaffold (TEST DOUBLE). Fill in the
real-robot paths; keep NEUXMIND_ADAPTER_BACKEND=double free of hardware."""
import json, os
from pathlib import Path

SPEC = json.loads((Path(__file__).with_name("adapter.json")).read_text())
IMPLEMENTED = %(implemented)r
DOUBLE = %(double)r
COMMANDS = %(commands)r


class %(cls)s:
    def __init__(self):
        self.backend = os.environ.get("NEUXMIND_ADAPTER_BACKEND", "robot")
        self.stopped = 0

    def manifest(self):
        return {"name": SPEC["name"], "capabilities": list(IMPLEMENTED)}

    def read(self, cap_id):
        if cap_id not in IMPLEMENTED:
            raise NotImplementedError(cap_id)
        if self.backend == "double":
            return dict(DOUBLE[cap_id])
        raise NotImplementedError("real-robot path for " + cap_id)

    def invoke(self, cap_id, args):
        if cap_id == "safety.stop":
            self.stop()
            return {"stopped": True}
        if self.backend == "double" and cap_id in COMMANDS and cap_id in IMPLEMENTED:
            return dict(COMMANDS[cap_id])
        raise NotImplementedError(cap_id)

    def stop(self):
        self.stopped += 1
'''


def scaffold(args):
    spec=json.loads(Path(args.spec).read_text())
    if spec.get('schema')!='neuxmind.adapter_scaffold.v1':print('错误：spec schema',file=sys.stderr);return 2
    out=Path(args.out)
    if out.exists() and any(out.iterdir()):print('错误：输出目录非空',file=sys.stderr);return 2
    module=spec['name'];cls=''.join(x.capitalize() for x in module.split('_'))+'Adapter'
    rows=spec['capabilities'];unknown=[r['id'] for r in rows if r['id'] not in caps.CAPABILITIES]
    if unknown:print('错误：unknown capability: '+','.join(unknown),file=sys.stderr);return 2
    missing=[f"{r['id']} 缺少必填参数 {f.name}" for r in rows for f in caps.CAPABILITIES[r['id']].params if f.required and f.name not in (r.get('params') or {})]
    if missing:print('错误：脚手架输入有误：'+'；'.join(missing),file=sys.stderr);return 2
    # Like the runtime: only ros2 hints with a template are implemented; the rest are TODO.
    implemented=[r['id'] for r in rows if str(r.get('implementation','todo')).split(':')[0]=='ros2' and r['id'] in ROS2_TEMPLATES];double={};commands={}
    for cid in caps.MANDATORY:
        if cid not in [r['id'] for r in rows]:rows.append({'id':cid,'params':{},'implementation':'todo'})
    for cid in implemented:
        cap=caps.CAPABILITIES[cid]
        if cap.kind in ('state','stream'):double[cid]={f.name:sample(f) for f in cap.outputs if f.required}
        elif cap.kind=='command' and cid!='safety.stop':commands[cid]={f.name:sample(f) for f in cap.outputs if f.required}
    (out/module).mkdir(parents=True);(out/'tests').mkdir()
    (out/module/'__init__.py').write_text('"""generated (test double)"""\n')
    (out/module/'adapter.json').write_text(json.dumps({**{k:spec.get(k) for k in ('name','vendor','model','family','instance_id','simulated','safety')},
        'capabilities':[{**r,'scaffold_status':'implemented' if r['id'] in implemented else 'todo'} for r in rows],'double':True},ensure_ascii=False,indent=2))
    (out/module/'adapter.py').write_text(ADAPTER%{'implemented':implemented,'double':double,'commands':commands,'cls':cls})
    (out/'README.md').write_text('# '+module+'（测试替身生成）\n')
    (out/'pyproject.toml').write_text('[project]\nname = "'+module+'"\nversion = "0.0.1"\n')
    (out/'tests'/'test_adapter.py').write_text('import unittest\nclass T(unittest.TestCase):\n    def test_placeholder(self):pass\n')
    print(json.dumps({'path':str(out),'module':module,'class_name':cls,'adapter':module+'.adapter:'+cls,'implemented':implemented,
                      'todo':[r['id'] for r in rows if r['id'] not in implemented],'mandatory_todo':[c for c in caps.MANDATORY if c not in implemented],
                      'files':['README.md','pyproject.toml',module+'/__init__.py',module+'/adapter.py',module+'/adapter.json','tests/test_adapter.py']},ensure_ascii=False))
    return 0


DISCLAIMER='本报告是能力一致性测试结果（测试替身）；它不等于现场验收证据（ADR-011）。'


def conformance(args):
    if args.level=='motion':print('错误：motion level is not available in the double',file=sys.stderr);return 2
    module_name,cls=args.adapter.split(':')
    try:
        module_dir=Path(importlib.util.find_spec(module_name.split('.')[0]).origin).parent
        # Test hook: a package containing HANG_CONFORMANCE never finishes (timeout/stop tests).
        if (module_dir/'HANG_CONFORMANCE').exists():time.sleep(600)
        adapter=getattr(importlib.import_module(module_name),cls)();declared=adapter.manifest()['capabilities']
    except (ImportError,AttributeError,NotImplementedError,RuntimeError,ValueError) as exc:
        print('错误：'+str(exc),file=sys.stderr);return 2          # like the runtime CLI: refused, no report
    missing=[c for c in caps.MANDATORY if c not in declared]
    if missing:print('错误：必备能力未实现 '+','.join(missing),file=sys.stderr);return 2
    cases=[]
    def case(cid,level,name,status,reason='',evidence=None):
        cases.append({'id':f'{level}.{cid}.{name}','capability':cid,'level':level,'name':name,'title':name,'status':status,'reason':reason,'evidence':evidence or {}})
    case('manifest','static','schema','passed',evidence={'capabilities':declared})
    for cid in declared:case(cid,'static','declaration','passed' if cid in caps.CAPABILITIES else 'failed','' if cid in caps.CAPABILITIES else 'not a standard capability')
    if args.level=='dry':
        for cid in declared:
            cap=caps.CAPABILITIES.get(cid)
            if cap is None:continue
            if cid=='safety.stop':
                t=time.monotonic();a=adapter.invoke(cid,{});b=adapter.invoke(cid,{})
                case(cid,'dry','idempotent_latched','passed' if a==b=={'stopped':True} else 'failed',evidence={'stop_s':round(time.monotonic()-t,4)})
            elif cap.kind in ('state','stream'):
                try:
                    t=time.monotonic();payload=adapter.read(cid);caps.validate_payload(cid,payload,'outputs')
                    case(cid,'dry','read','passed',evidence={'sample':payload,'latency_s':round(time.monotonic()-t,4)})
                except Exception as exc:case(cid,'dry','read','failed',str(exc)[:300])
            elif cid in ZERO:
                try:
                    out=adapter.invoke(cid,dict(ZERO[cid]));caps.validate_payload(cid,out,'outputs')
                    case(cid,'dry','zero_setpoint','passed',evidence={'command':ZERO[cid]})
                except Exception as exc:case(cid,'dry','zero_setpoint','failed',str(exc)[:300])
    def verdict(cid,level):
        mine=[c for c in cases if c['capability']==cid and c['level']==level]
        if cid not in declared:return {'status':'skipped','skip_kind':'not_applicable','reason':'本体未声明该能力（不支持或尚未实现）'}
        if not mine:return {'status':'skipped','skip_kind':'not_applicable','reason':'该级别没有此能力的测试'}
        bad=[c for c in mine if c['status']=='failed']
        return {'status':'failed','reason':bad[0]['reason']} if bad else {'status':'passed','reason':''}
    ran=['static']+(['dry'] if args.level=='dry' else [])
    rows=[{'id':cid,'title':cap.title,'kind':cap.kind,'safety':cap.safety,'declared':cid in declared,
           'levels':{lv:verdict(cid,lv) for lv in ran}} for cid,cap in caps.CAPABILITIES.items()]
    levels={}
    for lv in ('static','dry','motion'):
        mine=[c for c in cases if c['level']==lv];failed=sum(c['status']=='failed' for c in mine)
        ok=(lv in ran and not failed and (lv=='static' or levels['static']['ok'])) if lv in ran else None
        levels[lv]={'requested':lv in ran,'ran':lv in ran,'ok':ok,'passed':sum(c['status']=='passed' for c in mine),'failed':failed,
                    'skipped':0,'blocked':0,'blocked_reasons':[]}
    report={'schema':'conformance.report.v1','double':True,'conformance_id':'cf-double-'+args.level,'target':{'kind':'adapter','adapter':args.adapter},
            'robot':{'name':getattr(adapter,'__class__').__name__},'simulated':False,'evidence_kind':'conformance','field_acceptance':False,
            'disclaimer':DISCLAIMER,'level':args.level,'hardware_authorized':False,
            'static_ok':levels['static']['ok'],'dry_ok':levels['dry']['ok'],'motion_ok':None,'levels':levels,
            'prelatched':False,'aborted':None,'final_latched':False,'capabilities':rows,'cases':cases}
    Path(args.out).write_text(json.dumps(report,ensure_ascii=False,indent=2))
    return 0 if report[args.level+'_ok'] else 1


def main():
    parser=argparse.ArgumentParser();sub=parser.add_subparsers(dest='command',required=True)
    s=sub.add_parser('scaffold');s.add_argument('--spec',required=True);s.add_argument('--out',required=True)
    c=sub.add_parser('conformance');c.add_argument('--adapter',required=True);c.add_argument('--level',required=True,choices=('static','dry','motion'));c.add_argument('--out',required=True)
    args=parser.parse_args()
    return scaffold(args) if args.command=='scaffold' else conformance(args)


if __name__=='__main__':sys.exit(main())
